"""
Regenerate :code:`_generated.py` from :data:`model.GENERATED_FUNCTIONS`

Run :code:`python -m microscope_calibration.common.generate` after changing
:class:`~microscope_calibration.common.model.Model4DSTEM` and commit the result.
"""

from pathlib import Path

from microscope_calibration.common.model import GENERATED_FUNCTIONS
from microscope_calibration.util.codegen import render_module

TARGET = Path(__file__).parent / "_generated.py"

HEADER = """\
Generated by `python -m microscope_calibration.common.generate`. Don't edit by hand!

Functions derived symbolically from Model4DSTEM.trace(), see
microscope_calibration.common.model.GENERATED_FUNCTIONS.
tests/test_codegen.py verifies that this file is up to date."""


def render() -> str:
    return render_module(
        {name: derive() for name, derive in GENERATED_FUNCTIONS.items()},
        header=HEADER,
    )


if __name__ == "__main__":
    TARGET.write_text(render())
    print(f"Wrote {TARGET}")
