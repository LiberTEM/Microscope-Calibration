"""
Regenerate :code:`_generated.py` from :data:`GENERATED_FUNCTIONS`

Run :code:`python -m microscope_calibration.common.generate` after changing
:class:`~microscope_calibration.common.model.Model4DSTEM` and commit the result.
"""

from pathlib import Path

from microscope_calibration.common import model, stem_overfocus
from microscope_calibration.util.codegen import render_module


def _merge(*registries: dict) -> dict:
    res = {}
    for registry in registries:
        duplicates = set(res) & set(registry)
        if duplicates:
            raise ValueError(f"Duplicate generated function names {duplicates}")
        res.update(registry)
    return res


# Functions to generate, collected from the modules that use them
GENERATED_FUNCTIONS = _merge(
    model.GENERATED_FUNCTIONS,
    stem_overfocus.GENERATED_FUNCTIONS,
)

TARGET = Path(__file__).parent / "_generated.py"

HEADER = """\
Generated by `python -m microscope_calibration.common.generate`. Don't edit by hand!

Functions derived symbolically from Model4DSTEM.trace(), see
microscope_calibration.common.generate.GENERATED_FUNCTIONS.
tests/test_codegen.py verifies that this file is up to date."""


def render() -> str:
    return render_module(
        {name: derive() for name, derive in GENERATED_FUNCTIONS.items()},
        header=HEADER,
    )


if __name__ == "__main__":
    TARGET.write_text(render())
    print(f"Wrote {TARGET}")
